import { chromium, expect } from "@playwright/test";
import fs from "node:fs/promises";
import { IfcAPI, IFCBUILDINGSTOREY, IFCWALL } from "web-ifc";
const browser = await chromium.launch({ channel: "msedge", headless: true, args: ["--no-proxy-server"] });
const checks = [];
try {
  const page = await browser.newPage({ viewport: { width:1440, height:1000 } });
  const errors=[]; page.on("pageerror", e=>{errors.push(e.message); console.error(e.message);});
  const read=()=>page.evaluate(()=>{const id=localStorage.getItem("domus:active-project");return id?JSON.parse(localStorage.getItem("domus:local:v1:domus:project:"+id)):null;});
  const floors=async()=>{
    await page.getByRole("button",{name:"View settings",exact:true}).click();
    await page.locator(".floor-selector-trigger").click();
  };
  const close=()=>page.getByRole("button",{name:"Close view settings",exact:true}).click();
  await page.goto("http://127.0.0.1:3131/editor");
  await page.getByRole("button",{name:"Explore a furnished example"}).click();
  await page.waitForURL(/floor-plan/);
  await floors();
  await page.getByRole("button",{name:"Copy floor plan",exact:true}).click();
  await expect.poll(async()=>(await read())?.sceneData?.storeys?.length).toBe(2);
  const upper=(await read()).sceneData.activeStoreyId;
  const ground=(await read()).sceneData.storeys[0].id;
  await close();
  await page.getByRole("button",{name:"Add to plan",exact:true}).click();
  await page.locator(".editor-catalog-panel").getByRole("button",{name:/Søren Lounge Chair/}).first().click();
  await expect.poll(async()=>(await read()).sceneData.objects.length).toBe(4);
  expect((await read()).sceneData.objects.at(-1).storeyId).toBe(upper);
  const living = (await read()).floorPlanData.rooms.find(r=>r.type === "living");
  expect((await read()).sceneData.objects.at(-1).position.x).toBeCloseTo((living.bounds.x + living.bounds.width / 2) * 0.3048);
  expect((await read()).sceneData.objects.at(-1).position.z).toBeCloseTo((living.bounds.y + living.bounds.height / 2) * 0.3048);
  await page.reload();
  await expect(page.getByRole("button",{name:"Draw Structural Wall",exact:true})).toBeVisible();
  expect((await read()).sceneData.activeStoreyId).toBe(upper);
  expect((await read()).sceneData.objects.filter(o=>o.storeyId===ground)).toHaveLength(3);
  console.log("Checkpoint", checks.length + 1);
  checks.push("Copy floor plan, add upper-floor furniture, save and reload without moving ground-floor furniture");
  await floors();
  await page.getByRole("button",{name:"Level 1 - Ground 0.0 ft elevation",exact:true}).click();
  await close();
  await page.getByRole("button",{name:"Tools",exact:true}).click();
  await page.getByRole("button",{name:"Insert Staircase",exact:true}).click();
  const box=await page.locator(".konvajs-content canvas").first().boundingBox();
  await page.mouse.click(box.x+box.width*.35,box.y+box.height*.72);
  await page.keyboard.press("Escape");
  await expect.poll(async()=>(await read()).sceneData.staircases.length).toBe(1);
  expect((await read()).sceneData.staircases[0].endStoreyId).toBe(upper);
  console.log("Checkpoint", checks.length + 1);
  checks.push("Place stairs connected to the actual upper floor");
  // Open the project panel, which may already be open from selecting the new stair.
  if(await page.getByRole("button",{name:"Open project panel",exact:true}).isVisible())
    await page.getByRole("button",{name:"Open project panel",exact:true}).click();
  await page.getByRole("button",{name:"BOM & Export",exact:true}).click();
  const [download]=await Promise.all([page.waitForEvent("download"),page.getByRole("button",{name:"Export 3D BIM (IFC)",exact:true}).click()]);
  await download.saveAs("docs/portfolio-verification/two-floor.ifc");
  const api=new IfcAPI(); await api.Init();
  const model=api.OpenModel(new Uint8Array(await fs.readFile(await download.path())));
  expect(api.GetLineIDsWithType(model,IFCBUILDINGSTOREY).size()).toBe(2);
  expect(api.GetLineIDsWithType(model,IFCWALL).size()).toBeGreaterThan(10);
  api.CloseModel(model); api.Dispose();
  console.log("Checkpoint", checks.length + 1);
  checks.push("Download two-floor IFC through the editor and open it with an independent reader");
  await page.getByRole("button",{name:"3D View",exact:true}).click();
  await page.waitForTimeout(2000);
  await page.screenshot({path:"docs/portfolio-verification/two-floor-3d.png"});
  await floors();
  const upperName=(await read()).sceneData.storeys.find(s=>s.id===upper).name;
  await page.getByRole("button",{name:`Delete ${upperName}`,exact:true}).click();
  await close();
  await expect.poll(async()=>(await read()).sceneData.storeys.length).toBe(1);
  expect((await read()).sceneData.objects).toHaveLength(3);
  expect((await read()).sceneData.staircases).toHaveLength(0);
  await page.getByRole("button",{name:"Undo last change",exact:true}).click();
  await expect.poll(async()=>(await read()).sceneData.storeys.length).toBe(2);
  expect((await read()).sceneData.objects).toHaveLength(4);
  console.log("Checkpoint", checks.length + 1);
  checks.push("Delete an upper floor with its furniture and stairs, then restore all of them through undo");
  // Isolate blueprint handoff from the existing example project.
  const bim=await browser.newPage({viewport:{width:1440,height:1000}});
  bim.on("pageerror",e=>errors.push(e.message));
  await bim.goto("http://127.0.0.1:3131/bim-lift");
  await bim.getByRole("button",{name:"Try a sample blueprint",exact:true}).click();
  await bim.getByRole("button",{name:"Algorithmic Vectorize (Instant)",exact:true}).click();
  await expect(bim.getByText("Extrusion Output",{exact:true})).toBeVisible();
  await bim.getByRole("button",{name:"Open in 2D/3D CAD Studio",exact:true}).click();
  await bim.waitForURL(/floor-plan/);
  const readBim=()=>bim.evaluate(()=>{const id=localStorage.getItem("domus:active-project");return id?JSON.parse(localStorage.getItem("domus:local:v1:domus:project:"+id)):null;});
  await expect.poll(async()=>(await readBim())?.floorPlanData?.walls?.length??0).toBeGreaterThan(0);
  const wallCount=(await readBim()).floorPlanData.walls.length;
  await bim.reload();
  await expect(bim.getByRole("button",{name:"Draw Structural Wall",exact:true})).toBeVisible();
  expect((await readBim()).floorPlanData.walls.length).toBe(wallCount);
  console.log("Checkpoint", checks.length + 1);
  checks.push("Trace the bundled blueprint, hand it to the CAD editor, save and reload the resulting walls");
  expect(errors).toEqual([]);
  await fs.writeFile("docs/portfolio-verification/multi-floor-bim.json",JSON.stringify({checks,blueprintWallCount:wallCount,uncaughtErrors:errors},null,2));
  console.log("PASS "+checks.join("; "));
} finally { await browser.close(); }
